from rest_framework import viewsets, permissions, status
from rest_framework.views import APIView
from rest_framework.response import Response
from rest_framework_simplejwt.views import TokenObtainPairView
from django.contrib.auth import get_user_model

from .serializers import (
    CustomTokenObtainPairSerializer,
    UserSerializer,
    UserProfileSerializer,
)
from apps.common.permissions import IsAdminUserRole

User = get_user_model()

class CustomTokenObtainPairView(TokenObtainPairView):
    serializer_class = CustomTokenObtainPairSerializer


class CurrentUserView(APIView):
    """
    Returns the authenticated user's profile, active role, and institution details.
    """
    permission_classes = [permissions.IsAuthenticated]

    def get(self, request):
        serializer = UserProfileSerializer(request.user)
        return Response(serializer.data)


class UserViewSet(viewsets.ModelViewSet):
    """
    Admin user management viewset.
    Only system administrators can create, list, and modify user accounts and roles.
    """
    queryset = User.objects.all().select_related('institution')
    serializer_class = UserSerializer
    permission_classes = [IsAdminUserRole]
    search_fields = ['username', 'email', 'first_name', 'last_name', 'role']
    ordering_fields = ['date_joined', 'username', 'role']


class TotpSetupView(APIView):
    """
    Generates a TOTP secret and provisioning URI for setting up Authenticator apps (Google Authenticator, Microsoft Authenticator).
    """
    permission_classes = [permissions.IsAuthenticated]

    def get(self, request):
        user = request.user
        secret = user.generate_totp_secret()
        uri = user.get_totp_uri()
        return Response({
            'totp_enabled': user.totp_enabled,
            'secret': secret,
            'otpauth_uri': uri,
            'username': user.username,
        })


class TotpEnableView(APIView):
    """
    Enables TOTP 2FA by verifying the first 6-digit token generated by the authenticator app.
    """
    permission_classes = [permissions.IsAuthenticated]

    def post(self, request):
        from apps.common.audit import record_audit_event
        user = request.user
        raw_code = request.data.get('otp_code') or request.data.get('code') or request.data.get('totp_code') or ''
        otp_code = str(raw_code).strip()
        if not otp_code:
            return Response({'error': 'Six-digit OTP code is required.'}, status=status.HTTP_400_BAD_REQUEST)

        if not user.verify_totp(otp_code):
            return Response({'error': 'Invalid or expired TOTP verification code.'}, status=status.HTTP_400_BAD_REQUEST)

        user.totp_enabled = True
        user.save(update_fields=['totp_enabled'])

        record_audit_event(
            action='TOTP_2FA_ENABLED',
            entity_type='User',
            entity_id=str(user.id),
            actor=user,
            actor_username=user.username,
            actor_role=user.role,
            new_state={'totp_enabled': True}
        )

        return Response({
            'success': True,
            'totp_enabled': True,
            'message': 'Two-factor authentication (TOTP) successfully activated on your account.'
        })


class TotpDisableView(APIView):
    """
    Disables TOTP 2FA. Requires a valid 6-digit TOTP code or Admin authorization.
    """
    permission_classes = [permissions.IsAuthenticated]

    def post(self, request):
        from apps.common.audit import record_audit_event
        user = request.user
        otp_code = request.data.get('otp_code', '').strip()

        # Admin can disable without code if needed; otherwise require code
        if not user.is_admin_user:
            if not otp_code or not user.verify_totp(otp_code):
                return Response({'error': 'Valid verification code is required to disable 2FA.'}, status=status.HTTP_400_BAD_REQUEST)

        user.totp_enabled = False
        user.totp_secret = ''
        user.save(update_fields=['totp_enabled', 'totp_secret'])

        record_audit_event(
            action='TOTP_2FA_DISABLED',
            entity_type='User',
            entity_id=str(user.id),
            actor=user,
            actor_username=user.username,
            actor_role=user.role,
            new_state={'totp_enabled': False}
        )

        return Response({
            'success': True,
            'message': 'Two-factor authentication has been disabled.'
        })

